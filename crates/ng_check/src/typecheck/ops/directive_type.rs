// directive_type.ts:23 TcbDirectiveTypeOpBase
/// A `TcbOp` which constructs an instance of a directive. For generic directives, generic
/// parameters are set to `any` type.
pub struct TcbDirectiveTypeOpBase<'a, 'b> {
    tcb: TcbRef<'a, 'b>,
    scope: ScopeRef<'a, 'b>,
    node: DirectiveOwner<'a>,
    dir: DirectiveRef,
    directive_index: Option<usize>,
}

impl<'a, 'b> TcbDirectiveTypeOpBase<'a, 'b> {
    // directive_type.ts:24 constructor
    pub fn new(
        tcb: TcbRef<'a, 'b>,
        scope: ScopeRef<'a, 'b>,
        node: DirectiveOwner<'a>,
        dir: DirectiveRef,
        directive_index: Option<usize>,
    ) -> Self {
        Self { tcb, scope, node, dir, directive_index }
    }

    // directive_type.ts:34 optional
    fn optional() -> bool {
        // The statement generated by this operation is only used to declare the directive's type and
        // won't report diagnostics by itself, so the operation is marked as optional to avoid
        // generating declarations for directives that don't have any inputs/outputs.
        true
    }

    // directive_type.ts:41 execute
    fn execute(&self) -> TcbExpr {
        let raw_type = self.tcb.env.reference_tcb_value(&self.dir.r#ref);

        let r#type = match &self.dir.type_parameters {
            Some(type_parameters) if self.dir.is_generic && !type_parameters.is_empty() => {
                let type_arguments = vec!["any"; type_parameters.len()].join(", ");
                TcbExpr::new(format!("{}<{type_arguments}>", raw_type.p()))
            }
            _ => raw_type,
        };

        // (`this.node.startSourceSpan || this.node.sourceSpan`: the start span is always set.)
        let span: Span = match self.node {
            DirectiveOwner::HostElement(node) => node.source_span,
            DirectiveOwner::Element(node) => node.start_source_span,
            DirectiveOwner::Template(node) => node.start_source_span,
            DirectiveOwner::Component(node) => node.start_source_span,
            DirectiveOwner::Directive(node) => node.start_source_span,
        };

        let identifier = if self.dir.match_source == MatchSource::HostDirective {
            ExpressionIdentifier::HostDirective
        } else {
            ExpressionIdentifier::Directive
        };
        let id = TcbExpr::new(self.tcb.allocate_id())
            .add_expression_identifier(
                identifier,
                self.directive_index.map(|index| u32::try_from(index).expect("a directive index")),
            )
            .add_parse_span_info(span);
        self.scope.add_statement(declare_variable(&id, r#type));
        id
    }
}

// directive_type.ts:86 TcbNonGenericDirectiveTypeOp
/// A `TcbOp` which constructs an instance of a non-generic directive _without_ setting any of its
/// inputs.
///
/// Inputs are later set in the `TcbDirectiveInputsOp`. Type checking was found to be
/// faster when done in this way as opposed to `TcbDirectiveCtorOp` which is only necessary when the
/// directive is generic.
///
/// Executing this operation returns a reference to the directive instance variable with its inferred
/// type.
pub struct TcbNonGenericDirectiveTypeOp<'a, 'b>(TcbDirectiveTypeOpBase<'a, 'b>);

impl<'a, 'b> TcbNonGenericDirectiveTypeOp<'a, 'b> {
    // directive_type.ts:24 constructor (the base class's)
    pub fn new(
        tcb: TcbRef<'a, 'b>,
        scope: ScopeRef<'a, 'b>,
        node: DirectiveOwner<'a>,
        dir: DirectiveRef,
        directive_index: Option<usize>,
    ) -> Self {
        Self(TcbDirectiveTypeOpBase::new(tcb, scope, node, dir, directive_index))
    }
}

impl<'a, 'b> TcbOp<'a, 'b> for TcbNonGenericDirectiveTypeOp<'a, 'b> {
    fn optional(&self) -> bool {
        TcbDirectiveTypeOpBase::optional()
    }

    // directive_type.ts:91 execute
    /// Creates a variable declaration for this op's directive of the argument type. Returns the id of
    /// the newly created variable.
    fn execute(&self) -> Option<TcbExpr> {
        assert!(
            !self.0.dir.is_generic,
            "Assertion Error: expected {} not to be generic.",
            self.0.dir.r#ref.name
        );
        Some(self.0.execute())
    }
}

// directive_type.ts:107 TcbGenericDirectiveTypeWithAnyParamsOp
/// A `TcbOp` which constructs an instance of a generic directive with its generic parameters set
/// to `any` type.
///
/// This op is like `TcbDirectiveTypeOp`, except that generic parameters are set to
/// `any` type. This is used for situations where we want to avoid inlining.
///
/// Executing this operation returns a reference to the directive instance variable with its generic
/// type parameters set to `any`.
pub struct TcbGenericDirectiveTypeWithAnyParamsOp<'a, 'b>(TcbDirectiveTypeOpBase<'a, 'b>);

impl<'a, 'b> TcbGenericDirectiveTypeWithAnyParamsOp<'a, 'b> {
    // directive_type.ts:24 constructor (the base class's)
    pub fn new(
        tcb: TcbRef<'a, 'b>,
        scope: ScopeRef<'a, 'b>,
        node: DirectiveOwner<'a>,
        dir: DirectiveRef,
        directive_index: Option<usize>,
    ) -> Self {
        Self(TcbDirectiveTypeOpBase::new(tcb, scope, node, dir, directive_index))
    }
}

impl<'a, 'b> TcbOp<'a, 'b> for TcbGenericDirectiveTypeWithAnyParamsOp<'a, 'b> {
    fn optional(&self) -> bool {
        TcbDirectiveTypeOpBase::optional()
    }

    // directive_type.ts:108 execute
    fn execute(&self) -> Option<TcbExpr> {
        assert!(
            self.0
                .dir
                .type_parameters
                .as_ref()
                .is_some_and(|type_parameters| !type_parameters.is_empty()),
            "Assertion Error: expected typeParameters when creating a declaration for {}",
            self.0.dir.r#ref.name
        );

        Some(self.0.execute())
    }
}
