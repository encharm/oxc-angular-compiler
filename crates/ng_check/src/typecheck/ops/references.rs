// references.ts:26 LocalSymbol
#[derive(Debug, Clone, Copy)]
pub enum LocalSymbol<'a> {
    Element(&'a R3Element<'a>),
    Template(&'a R3Template<'a>),
    Variable(&'a R3Variable<'a>),
    LetDeclaration(&'a R3LetDeclaration<'a>),
    Reference(&'a R3Reference<'a>),
    HostElement(&'a R3HostElement<'a>),
    Component(&'a R3Component<'a>),
    Directive(&'a R3Directive<'a>),
}

impl<'a> LocalSymbol<'a> {
    /// The node's identity (`t2_api::node_key`)
    pub fn key(&self) -> usize {
        match self {
            Self::Element(n) => node_key(*n),
            Self::Template(n) => node_key(*n),
            Self::Variable(n) => node_key(*n),
            Self::LetDeclaration(n) => node_key(*n),
            Self::Reference(n) => node_key(*n),
            Self::HostElement(n) => node_key(*n),
            Self::Component(n) => node_key(*n),
            Self::Directive(n) => node_key(*n),
        }
    }

    /// The symbol as a node that directives are matched on (`Element | Template | Component | Directive |
    /// HostElement`), if it is one.
    pub fn as_directive_owner(&self) -> Option<DirectiveOwner<'a>> {
        match *self {
            Self::Element(n) => Some(DirectiveOwner::Element(n)),
            Self::Template(n) => Some(DirectiveOwner::Template(n)),
            Self::Component(n) => Some(DirectiveOwner::Component(n)),
            Self::Directive(n) => Some(DirectiveOwner::Directive(n)),
            Self::HostElement(n) => Some(DirectiveOwner::HostElement(n)),
            Self::Variable(_) | Self::LetDeclaration(_) | Self::Reference(_) => None,
        }
    }
}

impl<'a> From<TemplateEntity<'a>> for LocalSymbol<'a> {
    fn from(entity: TemplateEntity<'a>) -> Self {
        match entity {
            TemplateEntity::Reference(n) => Self::Reference(n),
            TemplateEntity::Variable(n) => Self::Variable(n),
            TemplateEntity::LetDeclaration(n) => Self::LetDeclaration(n),
        }
    }
}

impl<'a> From<DirectiveOwner<'a>> for LocalSymbol<'a> {
    fn from(owner: DirectiveOwner<'a>) -> Self {
        match owner {
            DirectiveOwner::Element(n) => Self::Element(n),
            DirectiveOwner::Template(n) => Self::Template(n),
            DirectiveOwner::Component(n) => Self::Component(n),
            DirectiveOwner::Directive(n) => Self::Directive(n),
            DirectiveOwner::HostElement(n) => Self::HostElement(n),
        }
    }
}

