// references.ts:56 TcbReferenceOp
/// A `TcbOp` which creates a variable for a local ref in a template.
/// The initializer for the variable is the variable expression for the directive, template, or
/// element the ref refers to. When the reference is used in the template, those TCB statements will
/// access this variable as well. For example:
/// ```ts
/// var _t1 = document.createElement('div');
/// var _t2 = _t1;
/// _t2.value
/// ```
/// This operation supports more fluent lookups for the `TemplateTypeChecker` when getting a symbol
/// for a reference. In most cases, this isn't essential; that is, the information for the symbol
/// could be gathered without this operation using the `BoundTarget`. However, for the case of
/// ng-template references, we will need this reference variable to not only provide a location in
/// the shim file, but also to narrow the variable to the correct `TemplateRef<T>` type rather than
/// `TemplateRef<any>` (this work is still TODO).
///
/// Executing this operation returns a reference to the directive instance variable with its inferred
/// type.
pub struct TcbReferenceOp<'a, 'b> {
    tcb: TcbRef<'a, 'b>,
    scope: ScopeRef<'a, 'b>,
    node: &'a R3Reference<'a>,
    /// `Element | Template | Component | Directive`
    host: DirectiveOwner<'a>,
    target: ReferenceOpTarget<'a>,
}

impl<'a, 'b> TcbReferenceOp<'a, 'b> {
    // references.ts:57 constructor
    pub fn new(
        tcb: TcbRef<'a, 'b>,
        scope: ScopeRef<'a, 'b>,
        node: &'a R3Reference<'a>,
        host: DirectiveOwner<'a>,
        target: ReferenceOpTarget<'a>,
    ) -> Self {
        Self { tcb, scope, node, host, target }
    }
}

impl<'a, 'b> TcbOp<'a, 'b> for TcbReferenceOp<'a, 'b> {
    // references.ts:69 optional
    // The statement generated by this operation is only used to for the Type Checker
    // so it can map a reference variable in the template directly to a node in the TCB.
    fn optional(&self) -> bool {
        true
    }

    // references.ts:71 execute
    fn execute(&self) -> Option<TcbExpr> {
        let id = TcbExpr::new(self.tcb.allocate_id());
        let mut initializer = match &self.target {
            ReferenceOpTarget::Template(target) => self.scope.resolve(LocalSymbol::Template(target), None),
            ReferenceOpTarget::Element(target) => self.scope.resolve(LocalSymbol::Element(target), None),
            ReferenceOpTarget::Directive(target) => self.scope.resolve(self.host.into(), Some(target)),
        };

        let config = self.tcb.env.config();
        // The reference is either to an element, an <ng-template> node, or to a directive on an
        // element or template.
        if (matches!(self.target, ReferenceOpTarget::Element(_)) && !config.check_type_of_dom_references)
            || !config.check_type_of_non_dom_references
        {
            // References to DOM nodes are pinned to 'any' when `checkTypeOfDomReferences` is `false`.
            // References to `TemplateRef`s and directives are pinned to 'any' when
            // `checkTypeOfNonDomReferences` is `false`.
            initializer = TcbExpr::new(format!("{} as any", initializer.p()));
        } else if matches!(self.target, ReferenceOpTarget::Template(_)) {
            // Direct references to an <ng-template> node simply require a value of type
            // `TemplateRef<any>`. To get this, an expression of the form
            // `(_t1 as any as TemplateRef<any>)` is constructed.
            let template_ref = self.tcb.env.reference_external_symbol("@angular/core", "TemplateRef");
            initializer = TcbExpr::new(format!("({} as any as {}<any>)", initializer.p(), template_ref.p()));
        }
        let initializer = initializer.add_parse_span_info(self.node.source_span);
        let id = id.add_parse_span_info(self.node.key_span);

        self.scope.add_statement(TcbExpr::new(format!("var {} = {}", id.p(), initializer.p())));
        Some(id)
    }
}

// references.ts:108 TcbInvalidReferenceOp
/// A `TcbOp` which is used when the target of a reference is missing. This operation generates a
/// variable of type any for usages of the invalid reference to resolve to. The invalid reference
/// itself is recorded out-of-band.
pub struct TcbInvalidReferenceOp<'a, 'b> {
    tcb: TcbRef<'a, 'b>,
    scope: ScopeRef<'a, 'b>,
}

impl<'a, 'b> TcbInvalidReferenceOp<'a, 'b> {
    // references.ts:109 constructor
    pub fn new(tcb: TcbRef<'a, 'b>, scope: ScopeRef<'a, 'b>) -> Self {
        Self { tcb, scope }
    }
}

impl<'a, 'b> TcbOp<'a, 'b> for TcbInvalidReferenceOp<'a, 'b> {
    // references.ts:117 optional
    // The declaration of a missing reference is only needed when the reference is resolved.
    fn optional(&self) -> bool {
        true
    }

    // references.ts:119 execute
    fn execute(&self) -> Option<TcbExpr> {
        let id = TcbExpr::new(self.tcb.allocate_id());
        self.scope.add_statement(TcbExpr::new(format!("var {} = null! as any", id.p())));
        Some(id)
    }
}
