// directive_constructor.ts:35 TcbDirectiveCtorOp
/// A `TcbOp` which constructs an instance of a directive with types inferred from its inputs. The
/// inputs themselves are not checked here; checking of inputs is achieved in `TcbDirectiveInputsOp`.
/// Any errors reported in this statement are ignored, as the type constructor call is only present
/// for type-inference.
///
/// When a Directive is generic, it is required that the TCB generates the instance using this method
/// in order to infer the type information correctly.
///
/// Executing this operation returns a reference to the directive instance variable with its inferred
/// type.
pub struct TcbDirectiveCtorOp<'a, 'b> {
    tcb: TcbRef<'a, 'b>,
    scope: ScopeRef<'a, 'b>,
    node: DirectiveOwner<'a>,
    dir: DirectiveRef,
    custom_form_control_type: Option<CustomFormControlType>,
    directive_index: Option<usize>,
}

impl<'a, 'b> TcbDirectiveCtorOp<'a, 'b> {
    // directive_constructor.ts:36 constructor
    pub fn new(
        tcb: TcbRef<'a, 'b>,
        scope: ScopeRef<'a, 'b>,
        node: DirectiveOwner<'a>,
        dir: DirectiveRef,
        custom_form_control_type: Option<CustomFormControlType>,
        directive_index: Option<usize>,
    ) -> Self {
        Self { tcb, scope, node, dir, custom_form_control_type, directive_index }
    }
}

impl<'a, 'b> TcbOp<'a, 'b> for TcbDirectiveCtorOp<'a, 'b> {
    // directive_constructor.ts:47 optional
    fn optional(&self) -> bool {
        // The statement generated by this operation is only used to infer the directive's type and
        // won't report diagnostics by itself, so the operation is marked as optional.
        true
    }

    // directive_constructor.ts:53 execute
    fn execute(&self) -> Option<TcbExpr> {
        let mut generic_inputs: Map<String, TcbDirectiveInput<'a>> = Map::default();
        let id = TcbExpr::new(self.tcb.allocate_id());
        let mut bound_attrs: Vec<TcbBoundAttribute<'a>>;
        let span: Span;

        if let DirectiveOwner::HostElement(node) = self.node {
            // Host elements can't bind to their own inputs so we don't resolve any.
            bound_attrs = Vec::new();
            span = node.source_span;
        } else {
            // (`this.node.startSourceSpan || this.node.sourceSpan`: the start span is always set.)
            span = match self.node {
                DirectiveOwner::Element(node) => node.start_source_span,
                DirectiveOwner::Template(node) => node.start_source_span,
                DirectiveOwner::Component(node) => node.start_source_span,
                DirectiveOwner::Directive(node) => node.start_source_span,
                DirectiveOwner::HostElement(node) => node.source_span,
            };
            bound_attrs = get_bound_attributes(&self.dir, self.node);

            if let Some(custom_form_control_type) = self.custom_form_control_type {
                let additional_bindings =
                    expand_bound_attributes_for_field(&self.dir, self.node, Some(custom_form_control_type));

                if let Some(additional_bindings) = additional_bindings {
                    bound_attrs.extend(additional_bindings);
                }
            }
        }

        let identifier = if self.dir.match_source == MatchSource::HostDirective {
            ExpressionIdentifier::HostDirective
        } else {
            ExpressionIdentifier::Directive
        };
        let id = id
            .add_expression_identifier(identifier, self.directive_index.map(|index| index as u32))
            .add_parse_span_info(span);

        for attr in &bound_attrs {
            // Skip text attributes if configured to do so.
            if !self.tcb.env.config().check_type_of_attributes
                && matches!(attr.value, TcbBoundAttributeValue::String(_))
            {
                continue;
            }
            for input in &attr.inputs {
                // Skip the field if an attribute has already been bound to it; we can't have a duplicate
                // key in the type constructor call.
                if generic_inputs.contains_key(&input.field_name) {
                    continue;
                }

                let expression = translate_input(&attr.value, &self.tcb, &self.scope);

                generic_inputs.insert(
                    input.field_name.clone(),
                    TcbDirectiveInput::Binding {
                        field: input.field_name.clone(),
                        expression,
                        original_expression: attr.value.clone(),
                        source_span: attr.source_span,
                        is_two_way_binding: input.is_two_way_binding,
                    },
                );
            }
        }

        // Add unset directive inputs for each of the remaining unset fields.
        for input in self.dir.inputs.iter() {
            let class_property_name = &input.input.class_property_name;
            if !generic_inputs.contains_key(class_property_name) {
                generic_inputs.insert(
                    class_property_name.clone(),
                    TcbDirectiveInput::Unset { field: class_property_name.clone() },
                );
            }
        }

        // Call the type constructor of the directive to infer a type, and assign the directive
        // instance.
        let inputs: Vec<TcbDirectiveInput<'a>> = generic_inputs.into_values().collect();
        let type_ctor = tcb_call_type_ctor(&self.dir, &self.tcb, &inputs);
        let type_ctor = type_ctor.mark_ignore_diagnostics();
        self.scope.add_statement(TcbExpr::new(format!("var {} = {}", id.p(), type_ctor.p())));
        Some(id)
    }

    // directive_constructor.ts:126 circularFallback
    fn circular_fallback(&self) -> CircularFallback<'a, 'b> {
        CircularFallback::Op(Box::new(TcbDirectiveCtorCircularFallbackOp::new(
            Rc::clone(&self.tcb),
            Rc::clone(&self.scope),
            Rc::clone(&self.dir),
        )))
    }
}

// directive_constructor.ts:145 TcbDirectiveCtorCircularFallbackOp
/// A `TcbOp` which is used to generate a fallback expression if the inference of a directive type
/// via `TcbDirectiveCtorOp` requires a reference to its own type. This can happen using a template
/// reference:
///
/// ```html
/// <some-cmp #ref [prop]="ref.foo"></some-cmp>
/// ```
///
/// In this case, `TcbDirectiveCtorCircularFallbackOp` will add a second inference of the directive
/// type to the type-check block, this time calling the directive's type constructor without any
/// input expressions. This infers the widest possible supertype for the directive, which is used to
/// resolve any recursive references required to infer the real type.
pub struct TcbDirectiveCtorCircularFallbackOp<'a, 'b> {
    tcb: TcbRef<'a, 'b>,
    scope: ScopeRef<'a, 'b>,
    dir: DirectiveRef,
}

impl<'a, 'b> TcbDirectiveCtorCircularFallbackOp<'a, 'b> {
    // directive_constructor.ts:146 constructor
    pub fn new(tcb: TcbRef<'a, 'b>, scope: ScopeRef<'a, 'b>, dir: DirectiveRef) -> Self {
        Self { tcb, scope, dir }
    }
}

impl<'a, 'b> TcbOp<'a, 'b> for TcbDirectiveCtorCircularFallbackOp<'a, 'b> {
    // directive_constructor.ts:154 optional
    fn optional(&self) -> bool {
        false
    }

    // directive_constructor.ts:158 execute
    fn execute(&self) -> Option<TcbExpr> {
        let id = self.tcb.allocate_id();
        let type_ctor = self.tcb.env.type_ctor_for(&self.dir);
        self.scope.add_statement(TcbExpr::new(format!("var {id} = {}(null!)", type_ctor.p())));
        Some(TcbExpr::new(id))
    }
}

// directive_constructor.ts:170 tcbCallTypeCtor
/// Call the type constructor of a directive instance on a given template node, inferring a type for
/// the directive instance from any bound inputs.
fn tcb_call_type_ctor(dir: &TcbDirectiveMetadata, tcb: &Context<'_, '_>, inputs: &[TcbDirectiveInput<'_>]) -> TcbExpr {
    let type_ctor = tcb.env.type_ctor_for(dir);
    let mut literal = String::from("{ ");

    // Construct an object literal containing each directive input.
    for (i, input) in inputs.iter().enumerate() {
        let is_last = i == inputs.len() - 1;

        match input {
            TcbDirectiveInput::Binding {
                field,
                expression,
                original_expression,
                source_span,
                is_two_way_binding,
            } => {
                let property_name = TcbExpr::quote_and_escape(field);
                // For bound inputs, the property is assigned the binding expression.
                let mut expr = widen_binding(expression.clone(), tcb, original_expression);

                if *is_two_way_binding && tcb.env.config().allow_signals_in_two_way_bindings {
                    expr = unwrap_writable_signal(&expr, tcb);
                }

                let assignment = TcbExpr::new(format!("{property_name}: {}", expr.wrap_for_type_checker().p()));
                let assignment = assignment.add_parse_span_info(*source_span);
                literal.push_str(&assignment.p());
            }
            TcbDirectiveInput::Unset { field } => {
                let property_name = TcbExpr::quote_and_escape(field);
                // A type constructor is required to be called with all input properties, so any unset
                // inputs are simply assigned a value of type `any` to ignore them.
                literal.push_str(&format!("{property_name}: 0 as any"));
            }
        }

        literal.push_str(&format!("{} ", if is_last { "" } else { "," }));
    }

    literal.push('}');

    // Call the `ngTypeCtor` method on the directive class, with an object literal argument created
    // from the matched inputs.
    TcbExpr::new(format!("{}({literal})", type_ctor.p()))
}
