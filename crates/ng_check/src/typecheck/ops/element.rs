use oxc_angular_compiler::ast::r3::R3Element;

use crate::typecheck::ops::base::{ScopeRef, TcbOp, TcbRef};
use crate::typecheck::ops::codegen::TcbExpr;

// element.ts:21 TcbElementOp
/// A `TcbOp` which creates an expression for a native DOM element (or web component) from a
/// `Element`.
///
/// Executing this operation returns a reference to the element variable.
pub struct TcbElementOp<'a, 'b> {
    tcb: TcbRef<'a, 'b>,
    scope: ScopeRef<'a, 'b>,
    element: &'a R3Element<'a>,
}

impl<'a, 'b> TcbElementOp<'a, 'b> {
    // element.ts:22 constructor
    pub fn new(tcb: TcbRef<'a, 'b>, scope: ScopeRef<'a, 'b>, element: &'a R3Element<'a>) -> Self {
        Self { tcb, scope, element }
    }
}

impl<'a, 'b> TcbOp<'a, 'b> for TcbElementOp<'a, 'b> {
    // element.ts:30 optional
    fn optional(&self) -> bool {
        // The statement generated by this operation is only used for type-inference of the DOM
        // element's type and won't report diagnostics by itself, so the operation is marked as optional
        // to avoid generating statements for DOM elements that are never referenced.
        true
    }

    // element.ts:37 execute
    fn execute(&self) -> Option<TcbExpr> {
        // (`this.element.startSourceSpan || this.element.sourceSpan`: the start span is always set.)
        let span = self.element.start_source_span;
        let id = self.tcb.allocate_id();
        let id_node = TcbExpr::new(id).add_parse_span_info(span);

        // Add the declaration of the element using document.createElement.
        let initializer =
            TcbExpr::new(format!("document.createElement(\"{}\")", self.element.name))
                .add_parse_span_info(span);
        let stmt = TcbExpr::new(format!("var {} = {}", id_node.p(), initializer.p()))
            .add_parse_span_info(span);
        self.scope.add_statement(stmt);
        Some(id_node)
    }
}
